const {
  createRunOncePlugin,
  withGradleProperties,
  withProjectBuildGradle,
} = require('@expo/config-plugins');

const ENABLED_PROPERTY = 'mindwtrNanoEnabled';
const MIN_SDK_PROPERTY = 'android.minSdkVersion';
const BASE_MIN_SDK_PROPERTY = 'mindwtrNanoBaseMinSdk';
const MIN_SDK = 26;
const START_MARKER = '// @generated by mindwtr-android-nano-clarification start';
const END_MARKER = '// @generated by mindwtr-android-nano-clarification end';

const resolveNanoClarificationEnabled = ({ requested, appVariant, fossBuild }) => (
  requested === true && appVariant === 'development' && fossBuild !== true
);

const upsertGradleProperty = (entries, key, value) => {
  const existing = entries.find((entry) => entry.type === 'property' && entry.key === key);
  if (existing) {
    existing.value = value;
  } else {
    entries.push({ type: 'property', key, value });
  }
  return entries;
};

const removeGradleProperty = (entries, key) => {
  const index = entries.findIndex((entry) => entry.type === 'property' && entry.key === key);
  if (index >= 0) entries.splice(index, 1);
};

const applyNanoMinSdkProperties = (entries, enabled) => {
  const minEntry = entries.find(
    (entry) => entry.type === 'property' && entry.key === MIN_SDK_PROPERTY,
  );
  const baseEntry = entries.find(
    (entry) => entry.type === 'property' && entry.key === BASE_MIN_SDK_PROPERTY,
  );
  const currentMin = Number.parseInt(minEntry?.value ?? '', 10);
  const baseMin = Number.parseInt(baseEntry?.value ?? '', 10);

  if (enabled) {
    if (!Number.isFinite(currentMin) || currentMin < MIN_SDK) {
      if (!Number.isFinite(baseMin) && Number.isFinite(currentMin)) {
        upsertGradleProperty(entries, BASE_MIN_SDK_PROPERTY, String(currentMin));
      }
      upsertGradleProperty(entries, MIN_SDK_PROPERTY, String(MIN_SDK));
    }
    return entries;
  }

  // Restore only the exact floor written by this plugin. If another config has
  // since selected a different or higher floor, preserve it.
  if (Number.isFinite(baseMin) && currentMin === MIN_SDK) {
    upsertGradleProperty(entries, MIN_SDK_PROPERTY, String(baseMin));
  }
  removeGradleProperty(entries, BASE_MIN_SDK_PROPERTY);
  return entries;
};

const buildMinSdkBlock = () => `${START_MARKER}
if ((findProperty('${ENABLED_PROPERTY}') ?: 'false').toBoolean()) {
  ext.minSdkVersion = Math.max((ext.minSdkVersion ?: 24) as int, ${MIN_SDK})
  subprojects {
    configurations.configureEach { configuration ->
      if (configuration.name.endsWith('CompileClasspath')) {
        configuration.resolutionStrategy.force 'org.jetbrains.kotlin:kotlin-stdlib:2.1.20'
      }
    }
  }
}
${END_MARKER}`;

const injectMinSdkGuard = (contents) => {
  const escapedStart = START_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const escapedEnd = END_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const existingBlock = new RegExp(`${escapedStart}[\\s\\S]*?${escapedEnd}\\n?`, 'g');
  const withoutExisting = contents.replace(existingBlock, '').trimEnd();
  return `${withoutExisting}\n\n${buildMinSdkBlock()}\n`;
};

function withAndroidNanoClarification(config, props = {}) {
  const enabled = props.enabled === true;
  config = withGradleProperties(config, (cfg) => {
    upsertGradleProperty(cfg.modResults, ENABLED_PROPERTY, String(enabled));
    applyNanoMinSdkProperties(cfg.modResults, enabled);
    return cfg;
  });
  return withProjectBuildGradle(config, (cfg) => {
    if (cfg.modResults.language === 'groovy') {
      cfg.modResults.contents = injectMinSdkGuard(cfg.modResults.contents);
    }
    return cfg;
  });
}

module.exports = createRunOncePlugin(
  withAndroidNanoClarification,
  'mindwtr-android-nano-clarification',
  '1.0.0',
);

module.exports.__testables = {
  ENABLED_PROPERTY,
  MIN_SDK_PROPERTY,
  BASE_MIN_SDK_PROPERTY,
  applyNanoMinSdkProperties,
  MIN_SDK,
  buildMinSdkBlock,
  injectMinSdkGuard,
  resolveNanoClarificationEnabled,
  upsertGradleProperty,
};
